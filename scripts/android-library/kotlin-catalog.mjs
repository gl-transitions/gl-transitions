// Renders the Kotlin catalog of the Android library (android/gl-transitions/src/main/kotlin/com/
// gltransitions/generated/Catalog.kt) from the built npm package: one function per transition (a
// single list literal would exceed the JVM's method size limit), whose AGSL source the library
// reads from its resources.

const TYPES = {
  float: ["FLOAT", 1, false],
  vec2: ["VEC2", 2, false],
  vec3: ["VEC3", 3, false],
  vec4: ["VEC4", 4, false],
  int: ["INT", 1, true],
  ivec2: ["IVEC2", 2, true],
  ivec3: ["IVEC3", 3, true],
  ivec4: ["IVEC4", 4, true],
  bool: ["BOOL", 1, false],
};

// A Kotlin string literal: `$` would start a template.
function str(s) {
  const escaped = s
    .replace(/[\\"$]/g, "\\$&")
    .replace(/[\u0000-\u001f\u007f]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
  return `"${escaped}"`;
}

function float(n) {
  if (typeof n !== "number" || !Number.isFinite(n)) throw new Error(`not a finite number: ${n}`);
  const s = String(n);
  return `${/[.e]/.test(s) ? s : `${s}.0`}f`;
}

function int(n) {
  if (!Number.isInteger(n)) throw new Error(`not an integer: ${n}`);
  if (n < -(2 ** 31) || n >= 2 ** 31) throw new Error(`out of the Int range: ${n}`);
  return String(n);
}

const optional = (value, render) => (value === undefined || value === null ? "null" : render(value));

function value(type, def, where) {
  const spec = TYPES[type];
  if (!spec) throw new Error(`${where}: unsupported parameter type ${type}`);
  const [, count, integer] = spec;
  if (type === "bool") {
    if (typeof def !== "boolean")
      throw new Error(`${where}: bool default must be a boolean, got ${JSON.stringify(def)}`);
    return `ParamValue.bool(${def})`;
  }
  const scalar = integer ? int : float;
  const components = count === 1 ? [def] : def;
  if (count === 1 ? typeof def !== "number" : !Array.isArray(def) || def.length !== count) {
    throw new Error(`${where}: ${type} default must have ${count} component(s), got ${JSON.stringify(def)}`);
  }
  return `ParamValue.${type}(${components.map(scalar).join(", ")})`;
}

function param(name, p, where) {
  if (!TYPES[p.type]) throw new Error(`${where}.${name}: unsupported parameter type ${p.type}`);
  return `Param(${str(name)}, ParamType.${TYPES[p.type][0]}, ${value(p.type, p.default, `${where}.${name}`)}, ${optional(p.min, float)}, ${optional(p.max, float)}, ${optional(p.step, float)}, ${p.color === true}, ${optional(p.description, str)})`;
}

// `transitions`: gl-transitions.json; `agsl`: the names of the transitions that have an SkSL source;
// `version`: the npm package version. Transitions without one are left out.
function renderCatalog({ transitions, agsl, version }) {
  const sorted = transitions.filter((t) => agsl.has(t.name)).sort((a, b) => (a.name < b.name ? -1 : 1));
  const functions = sorted.map((t, i) => {
    const params = Object.entries(t.params ?? {}).map(([name, p]) => param(name, p, t.name));
    const list = (items) => (items.length ? `listOf(${items.join(", ")})` : "emptyList()");
    return `private fun transition${i}() = Transition(
    ${str(t.name)},
    ${str(t.author ?? "")},
    ${str(t.license ?? "")},
    ${optional(t.description, str)},
    ${list((t.tags ?? []).map(str))},
    ${params.length ? `listOf(\n        ${params.join(",\n        ")},\n    )` : "emptyList()"},
    ${list((t.textures ?? []).map(str))},
)`;
  });
  return `// Generated by scripts/android-library/build-android-library.mjs from the gl-transitions npm package ${version}.
// Do not edit: run \`pnpm run build && pnpm run build:android\` instead.
package com.gltransitions.generated

import com.gltransitions.Param
import com.gltransitions.ParamType
import com.gltransitions.ParamValue
import com.gltransitions.Transition

internal const val CATALOG_VERSION = ${str(version)}

internal fun catalog(): List<Transition> = listOf(
    ${sorted.map((_, i) => `transition${i}()`).join(",\n    ")},
)

${functions.join("\n\n")}
`;
}

// The transitions under another license than the library's MIT one, with their original source:
// its comments hold the copyright notice and conditions, which the AGSL translation loses.
function renderNotices(transitions) {
  const others = transitions.filter((t) => t.license !== "MIT").sort((a, b) => (a.name < b.name ? -1 : 1));
  return `# Licenses of the transitions

The library is MIT licensed, and so are its transitions except the ones below. Each one keeps its
license in its AGSL translation: here is its original source, with its copyright notice and
license conditions.
${others.map((t) => `\n## ${t.name}\n\n${t.license}, by ${t.author}.\n\n\`\`\`glsl\n${t.glsl.trimEnd()}\n\`\`\`\n`).join("")}`;
}

export { renderCatalog, renderNotices, str };
