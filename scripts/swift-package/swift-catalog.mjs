// Renders the Swift catalog of the GLTransitions package (swift/Sources/GLTransitions/Generated/
// Catalog.swift) from the built npm package: one `GLTransition` per entry of gl-transitions.json,
// with its Metal source and its uniform layout from layouts.json.

// GLSL parameter types → [Swift `ParamType` case, component count, integer].
const TYPES = {
  float: ["float", 1, false],
  vec2: ["vec2", 2, false],
  vec3: ["vec3", 3, false],
  vec4: ["vec4", 4, false],
  int: ["int", 1, true],
  ivec2: ["ivec2", 2, true],
  ivec3: ["ivec3", 3, true],
  ivec4: ["ivec4", 4, true],
  bool: ["bool", 1, false],
};

// A Swift string literal; control characters are written as \u{…}.
function str(s) {
  const escaped = s
    .replace(/[\\"]/g, "\\$&")
    .replace(/[\u0000-\u001f\u007f]/g, (c) => `\\u{${c.charCodeAt(0).toString(16)}}`);
  return `"${escaped}"`;
}

// A raw multi-line literal for the shader sources, which Swift then reads verbatim.
function raw(s) {
  if (s.includes('"""#')) throw new Error('a shader source contains """#');
  return `#"""\n${s.replace(/\r\n/g, "\n").trimEnd()}\n"""#`;
}

function float(n) {
  if (typeof n !== "number" || !Number.isFinite(n)) throw new Error(`not a finite number: ${n}`);
  return String(n);
}

function int(n) {
  if (!Number.isInteger(n)) throw new Error(`not an integer: ${n}`);
  if (n < -(2 ** 31) || n >= 2 ** 31) throw new Error(`out of the Int32 range: ${n}`);
  return String(n);
}

const optional = (value, render) => (value === undefined || value === null ? "nil" : render(value));

function value(type, def, where) {
  const spec = TYPES[type];
  if (!spec) throw new Error(`${where}: unsupported parameter type ${type}`);
  const [kase, count, integer] = spec;
  if (type === "bool") {
    if (typeof def !== "boolean")
      throw new Error(`${where}: bool default must be a boolean, got ${JSON.stringify(def)}`);
    return `.bool(${def})`;
  }
  const scalar = integer ? int : float;
  if (count === 1) {
    if (typeof def !== "number")
      throw new Error(`${where}: ${type} default must be a number, got ${JSON.stringify(def)}`);
    return `.${kase}(${scalar(def)})`;
  }
  if (!Array.isArray(def) || def.length !== count) {
    throw new Error(`${where}: ${type} default must have ${count} components, got ${JSON.stringify(def)}`);
  }
  // Explicit SIMD types keep the type checker fast on this large file.
  return `.${kase}(SIMD${count}<${integer ? "Int32" : "Float"}>(${def.map(scalar).join(", ")}))`;
}

function param(name, p, where) {
  if (!TYPES[p.type]) throw new Error(`${where}.${name}: unsupported parameter type ${p.type}`);
  return `Param(name: ${str(name)}, type: .${TYPES[p.type][0]}, defaultValue: ${value(p.type, p.default, `${where}.${name}`)}, min: ${optional(p.min, float)}, max: ${optional(p.max, float)}, step: ${optional(p.step, float)}, isColor: ${p.color === true}, description: ${optional(p.description, str)})`;
}

function layout(l, where) {
  if (!l) throw new Error(`${where}: no uniform layout`);
  const fields = l.uniforms.map(({ name, type, offset }) => {
    if (!TYPES[type]) throw new Error(`${where}: unsupported uniform type ${type}`);
    return `UniformField(name: ${str(name)}, type: .${TYPES[type][0]}, offset: ${int(offset)})`;
  });
  return `UniformLayout(size: ${int(l.size)}, fields: [${fields.join(", ")}])`;
}

// `transitions`: gl-transitions.json; `layouts`: layouts.json; `msl`: { [name]: Metal source } of
// the transitions that have one; `version`: the npm package version. Transitions without a Metal
// source are left out.
function renderCatalog({ transitions, layouts, msl, version }) {
  const sorted = transitions.filter((t) => msl[t.name] !== undefined).sort((a, b) => (a.name < b.name ? -1 : 1));
  // One constant per transition: a single array literal of them would be slow to type-check.
  const entries = sorted.map((t, i) => {
    const params = Object.entries(t.params ?? {}).map(([name, p]) => param(name, p, t.name));
    return `private let transition${i} = GLTransition(
    name: ${str(t.name)},
    author: ${str(t.author ?? "")},
    license: ${str(t.license ?? "")},
    description: ${optional(t.description, str)},
    tags: [${(t.tags ?? []).map(str).join(", ")}],
    params: [${params.length ? `\n        ${params.join(",\n        ")},\n    ` : ""}],
    textures: [${(t.textures ?? []).map(str).join(", ")}],
    uniformLayout: ${layout(layouts[t.name], t.name)},
    metalSource: ${raw(msl[t.name])}
)`;
  });
  return `// Generated by scripts/swift-package/build-swift-package.mjs from the gl-transitions npm package ${version}.
// Do not edit: run \`pnpm run build && pnpm run build:swift\` instead.

extension GLTransitions {
    /// Version of the gl-transitions npm package the transitions come from.
    public static let catalogVersion = ${str(version)}

    /// Every transition, sorted by name.
    public static let all: [GLTransition] = [${sorted.map((_, i) => `transition${i}`).join(", ")}]
}

${entries.join("\n\n")}
`;
}

// The transitions under another license than the package's MIT one, with their original source:
// its comments hold the copyright notice and conditions, which the Metal translation loses.
function renderNotices(transitions) {
  const others = transitions.filter((t) => t.license !== "MIT").sort((a, b) => (a.name < b.name ? -1 : 1));
  return `# Licenses of the transitions

The package is MIT licensed (LICENSE), and so are its transitions except the ones below. Each one
keeps its license in its Metal translation: here is its original source, with its copyright notice
and license conditions.
${others
  .map(
    (t) => `
## ${t.name}

${t.license}, by ${t.author}.

\`\`\`glsl
${t.glsl.trimEnd()}
\`\`\`
`,
  )
  .join("")}`;
}

export { renderCatalog, renderNotices, str };
