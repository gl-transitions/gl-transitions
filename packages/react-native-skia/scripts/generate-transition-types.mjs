#!/usr/bin/env node
// Generates src/transition-types.generated.ts from the transitions folder: the known
// transition names and the parameters of each, so `name` autocompletes and `params`
// is type-checked. Transitions added to gl-transitions later still work by name.

import fs from "node:fs";
import path from "node:path";
import { parseTransition } from "../../../scripts/catalog/parse-transition.mjs";

const ROOT = path.join(import.meta.dirname, "..", "..", "..");
const OUT = path.join(import.meta.dirname, "..", "src", "transition-types.generated.ts");

const COMPONENTS = { vec2: 2, vec3: 3, vec4: 4, ivec2: 2, ivec3: 3, ivec4: 4, mat2: 4, mat3: 9, mat4: 16 };

function tsType(type) {
  if (type === "bool") return "boolean";
  if (type === "float" || type === "int") return "number";
  return `readonly [${Array(COMPONENTS[type]).fill("number").join(", ")}]`;
}

const doc = (text, indent) => (text ? `${indent}/** ${text.replace(/\*\//g, "*\\/")} */\n` : "");

const dir = path.join(ROOT, "transitions");
const entries = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".glsl"))
  .sort()
  .map((file) => {
    const { transition } = parseTransition(fs.readFileSync(path.join(dir, file), "utf8"), file);
    const params = Object.entries(transition.params)
      .map(([name, p]) => `${doc(p.description, "    ")}    ${name}: ${tsType(p.type)};\n`)
      .join("");
    return `${doc(transition.description, "  ")}  ${JSON.stringify(transition.name)}: {${params ? `\n${params}  ` : ""}};\n`;
  });

fs.writeFileSync(
  OUT,
  `// Generated by scripts/generate-transition-types.mjs from the transitions folder. Do not edit.

/** Parameters of every transition known when this package was built, by transition name. */
export interface TransitionParamsByName {
${entries.join("")}}
`,
);
